#!/usr/bin/env python3
"""G16J: build the development-board vendor prefix table from the public IEEE registry.

    firmware/tools/make_oui_table.py <oui.txt> > firmware/components/guardian_core/include/guardian/oui_table.hpp

Input: the IEEE "oui.txt" (https://standards-oui.ieee.org/oui/oui.txt), kept in the store under
third-party/ieee-oui-<date>/. Output: the sorted 24-bit prefixes registered to Espressif
(the maker of the ESP32 / ESP8266 radio modules), one hex literal per entry, for
guardian::board_vendor() (components/guardian_core/threats.cpp). Facts from a public
registry, no code. A prefix says who was ASSIGNED the address block, never who is transmitting:
addresses are spoofable and most tools can randomize them.
"""
import hashlib, re, sys

def prefixes(text, vendor='espressif'):
    out = set()
    for m in re.finditer(r'^([0-9A-F]{6})\s+\(base 16\)\s+(.*)$', text, re.M):
        if vendor in m.group(2).lower():
            out.add(int(m.group(1), 16))
    return sorted(out)

def render(values, sha, name):
    lines = ['#pragma once', '',
             f'// Generated by firmware/tools/make_oui_table.py from {name} (sha256 {sha}).',
             f'// {len(values)} address prefixes the public IEEE registry assigns to Espressif, sorted. Do not edit by hand.',
             '// A prefix says who was ASSIGNED the block, never who is transmitting.',
             '#include <cstdint>', '', 'namespace guardian::detail {', 'inline constexpr std::uint32_t board_vendor_prefixes[] = {']
    for i in range(0, len(values), 10):
        lines.append('    ' + ' '.join(f'0x{v:06X},' for v in values[i:i + 10]))
    lines += ['};', '} // namespace guardian::detail']
    return '\n'.join(lines) + '\n'

def main(argv):
    if len(argv) != 2:
        sys.stderr.write(__doc__); return 2
    data = open(argv[1], 'rb').read()
    values = prefixes(data.decode('utf-8', 'replace'))
    if len(values) < 50:
        sys.stderr.write(f'only {len(values)} prefixes found: not the IEEE registry file?\n'); return 1
    sys.stdout.write(render(values, hashlib.sha256(data).hexdigest(), 'IEEE oui.txt fetched 2026-11-18'))
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv))
